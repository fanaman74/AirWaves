// Refresh the price list shipped with Scarlet from LiteLLM's public price file.
// Run by the weekly "Model prices" workflow; it opens a PR when anything changed.
//   pnpm --filter @scarlet/server prices:update
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { PRICE_LIST_URL, pickPrices, type PriceList } from "../src/repo/modelPrices.js";
import { MODEL_PRICES_SNAPSHOT } from "../src/repo/modelPrices.generated.js";

const out = fileURLToPath(new URL("../src/repo/modelPrices.generated.ts", import.meta.url));
const res = await fetch(PRICE_LIST_URL, { signal: AbortSignal.timeout(60_000) });
if (!res.ok) throw new Error(`${PRICE_LIST_URL}: HTTP ${res.status}`);
const models = pickPrices(await res.json());
if (Object.keys(models).length < 20) throw new Error(`Only ${Object.keys(models).length} models in the price list; leaving the snapshot as it is.`);

if (JSON.stringify(models) === JSON.stringify(MODEL_PRICES_SNAPSHOT.models)) {
  console.log("Model prices unchanged.");
  process.exit(0);
}
const before = MODEL_PRICES_SNAPSHOT.models;
const added = Object.keys(models).filter(m => !before[m]);
const changed = Object.keys(models).filter(m => before[m] && JSON.stringify(before[m]) !== JSON.stringify(models[m]));
const removed = Object.keys(before).filter(m => !models[m]);

const list: PriceList = { fetchedAt: new Date().toISOString(), models };
await writeFile(out, `// Generated by scripts/update-model-prices.ts from ${PRICE_LIST_URL}. Do not edit by hand:
// Scarlet's own rates, which take precedence, are in apiTokenCost.ts.
import type { PriceList } from "./modelPrices.js";

export const MODEL_PRICES_SNAPSHOT: PriceList = {
  fetchedAt: ${JSON.stringify(list.fetchedAt)},
  models: {
${Object.entries(models).map(([id, price]) => `    ${JSON.stringify(id)}: ${JSON.stringify(price)},`).join("\n")}
  },
};
`);
for (const [label, ids] of [["Added", added], ["Changed", changed], ["Removed", removed]] as const) {
  if (ids.length) console.log(`${label}: ${ids.join(", ")}`);
}
